"""Take a version of checkout-spec into spec/ (PORTING.md, "The pinned copy of the specification").

    python scripts/pin_spec.py <path to a checkout-spec clone> <commit>

Copies the files manifest.json lists, at that commit, checking each SHA-256; writes spec/PIN.json;
writes src/sattleme_checkout/_currencies.py from currencies.json. The copy is never edited
by hand: run this, then make the code pass the new vectors, in one pull request.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"
CURRENCIES = ROOT / "src" / "sattleme_checkout" / "_currencies.py"
REPOSITORY = "https://github.com/sattleme/checkout-spec"


def _show(clone: Path, commit: str, path: str) -> bytes:
    return subprocess.run(  # noqa: S603 - fixed arguments, a local clone
        ["git", "-C", str(clone), "show", f"{commit}:{path}"],  # noqa: S607
        check=True,
        capture_output=True,
    ).stdout


def write_currencies(table: dict[str, int], source: str, published: str) -> None:
    lines = [
        '"""The currencies an order may be priced in, with their decimals (SPEC.md §25).',
        "",
        "Generated by scripts/pin_spec.py from spec/currencies.json; never edited by hand.",
        f"ISO 4217 List One published {published}, source:",
        source,
        '"""',
        "",
        "from typing import Final",
        "",
        "CURRENCIES: Final[dict[str, int]] = {",
        *(f'    "{code}": {digits},' for code, digits in sorted(table.items())),
        "}",
        "",
    ]
    CURRENCIES.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main(clone: Path, commit: str) -> None:
    if len(commit) != 40:
        sys.exit("give the full 40-character commit")
    manifest = json.loads(_show(clone, commit, "manifest.json"))
    if SPEC.exists():
        shutil.rmtree(SPEC)
    for relative, digest in manifest["files"].items():
        data = _show(clone, commit, relative)
        if hashlib.sha256(data).hexdigest() != digest:
            sys.exit(f"{relative}: its SHA-256 is not the manifest's")
        target = SPEC / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    pin = {
        "repository": REPOSITORY,
        "commit": commit,
        "version": manifest["version"],
        "protocol": manifest["protocol"],
        "files": manifest["files"],
    }
    (SPEC / "PIN.json").write_text(
        json.dumps(pin, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    currencies = json.loads((SPEC / "currencies.json").read_text(encoding="utf-8"))
    write_currencies(currencies["currencies"], currencies["source"], currencies["published"])
    print(f"spec/ now holds checkout-spec {manifest['version']} ({commit})")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), sys.argv[2])
